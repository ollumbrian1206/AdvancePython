# A variable is a storage location used to hold/store values.
# Rules for naming variables:
# 1. Variable names should not use keywords/reserved words.
# 2. Variable names should not start with a number.
# 3. If a variable name has more than one word, use an underscore to join the words.

name1 = "Eren Yeager"

print(name1)

"""Variables hold data of different types ie String, Int, Float, List, Dictionary, Set, Boolean, Tuple"""

