# While loop.
# It is used when the looping number is known beforehand.
"""
The structure of a while loop is given below:
Initializing a variable,
While keyword,
Condition to be checked,
Increment/decrement.
"""

number = 0

while number <= 10:
    print(number)
    number = number + 1

print("===========================")
# Come up with a decrement example.
newnumber = 8

while newnumber >= 1:
    print(newnumber)
    newnumber = newnumber - 1