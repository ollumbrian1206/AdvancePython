# Comparison Operators - They are used in comparing two values and return a boolean value. They include: <, >, <=, >=, ==, !=

print(5 > 3)
print(5 < 3)
print(5 >= 3)
print(5 <= 3)
print(5 == 3)
print(5 != 3)

# Logical Operators 
# Logical AND - Evaluates to true if both statements are true.
print((3 > 2) and (2 < 3))

# Logical OR - Evaluates to true if one of the statements is true.
print((3 > 2) or (3 < 2))

# Logical NOT - It negates a statement. If a statement is true, it becomes false and vice versa.
print(not(3 > 2))